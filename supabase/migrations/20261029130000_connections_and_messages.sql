-- Connections (intros) and messages between members, plus every member's conversation with the
-- admins. Clients read the three tables directly (select only, under RLS) so RxDB can replicate
-- them; every write goes through the functions below. See "connections", "connection_secrets",
-- "messages" and "Messaging sync" in docs/database.md.

-- tables -------------------------------------------------------------------

create type public.connection_status as enum (
  'pending',   -- intro sent
  'accepted',  -- intro accepted, so both can message
  'ended'      -- ended by one of the two (an `ended` message records who and when); final
);

-- One per pair of people in touch. Declining an intro isn't a status, because the initiator can
-- read this row: it's in the recipient's connection_secrets row.
create table public.connections (
  initiator_id uuid not null references public.profiles (id) on delete cascade,
  recipient_id uuid not null references public.profiles (id) on delete cascade,
  status public.connection_status not null default 'pending',
  -- What the initiator wants to connect on. Empty only for the connections with admins.
  looking_for text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (initiator_id, recipient_id),
  check (initiator_id <> recipient_id)
);

-- At most one connection between two people, whoever started it.
create unique index connections_pair
  on public.connections (least(initiator_id, recipient_id), greatest(initiator_id, recipient_id));
create index connections_initiator_updated_at on public.connections (initiator_id, updated_at);
create index connections_recipient_updated_at on public.connections (recipient_id, updated_at);

-- One user's private side of a connection, or of a possible one (a dismissal in search needs no
-- connection). Only user_id ever sees it.
create table public.connection_secrets (
  user_id uuid not null references public.profiles (id) on delete cascade,
  other_user_id uuid not null references public.profiles (id) on delete cascade,
  dismissed_at timestamptz,
  declined_at timestamptz,
  -- Read watermark: messages from the other person after it are unread.
  last_read_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, other_user_id),
  check (user_id <> other_user_id)
);

create index connection_secrets_user_updated_at on public.connection_secrets (user_id, updated_at);

create table public.messages (
  -- Generated by the client for send_message(), so a retried send doesn't create a duplicate.
  -- The messages the server writes (intros, `ended`) use the default.
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references public.profiles (id) on delete cascade,
  recipient_id uuid not null references public.profiles (id) on delete cascade,
  -- {"type": "text", "text": "…"} from the sender (see check_message_content()), or
  -- {"type": "ended"}, written by end_connection() when the sender ended the connection.
  content jsonb not null,
  created_at timestamptz not null default now(),
  -- For replication: deletions are soft (with the content cleared) so they replicate too.
  updated_at timestamptz not null default now(),
  deleted boolean not null default false
);

create index messages_sender_updated_at on public.messages (sender_id, updated_at, id);
create index messages_recipient_updated_at on public.messages (recipient_id, updated_at, id);

create trigger connections_set_updated_at
  before update on public.connections
  for each row execute function public.set_updated_at();

create trigger connection_secrets_set_updated_at
  before update on public.connection_secrets
  for each row execute function public.set_updated_at();

create trigger messages_set_updated_at
  before update on public.messages
  for each row execute function public.set_updated_at();

-- Clients may only read their own rows, so RxDB can pull them. Writes go through the functions.
alter table public.connections enable row level security;
alter table public.connection_secrets enable row level security;
alter table public.messages enable row level security;
revoke all on public.connections, public.connection_secrets, public.messages from anon, authenticated;
grant select on public.connections, public.connection_secrets, public.messages to authenticated;
grant all on public.connections, public.connection_secrets, public.messages to service_role;

create policy "connections_select_own" on public.connections
  for select to authenticated using ((select auth.uid()) in (initiator_id, recipient_id));

create policy "connection_secrets_select_own" on public.connection_secrets
  for select to authenticated using (user_id = (select auth.uid()));

create policy "messages_select_own" on public.messages
  for select to authenticated using ((select auth.uid()) in (sender_id, recipient_id));

-- helpers -------------------------------------------------------------------

-- Who may send messages and accept intros, by profile status: members whose profile is live, and
-- the admins. Not `disabled`: a hidden profile can't message until it's unhidden.
create or replace function public.can_message(p_status public.profile_status)
returns boolean
language sql
immutable
set search_path = public
as $$
  select p_status in ('active', 'admin');
$$;

-- Messages are JSON so other kinds (images, reactions) can be added later. Members can send only
-- text for now: 1 to 2000 characters, not just whitespace. (`ended` messages come only from
-- end_connection().)
create or replace function public.check_message_content(p_content jsonb)
returns void
language plpgsql
immutable
set search_path = public
as $$
begin
  if not coalesce(
    case when jsonb_typeof(p_content) = 'object' then
      p_content ->> 'type' = 'text'
      and p_content - 'type' - 'text' = '{}'
      and jsonb_typeof(p_content -> 'text') = 'string'
      and p_content ->> 'text' ~ '\S'
      and length(p_content ->> 'text') <= 2000
    end,
    false
  ) then
    raise exception 'A message must be a text of 1 to 2000 characters.';
  end if;
end;
$$;

-- Connects a member with every admin (one for now), as an accepted connection, so they can
-- message each other like any connection. Does nothing for connections that already exist, so it
-- can be run again after adding an admin (see "Admins" in docs/database.md).
create or replace function public.connect_with_admins(p_member_id uuid)
returns void
language sql
volatile
security definer
set search_path = public
as $$
  insert into public.connections (initiator_id, recipient_id, status)
  select id, p_member_id, 'accepted' from public.profiles where status = 'admin'
  on conflict do nothing;

  insert into public.connection_secrets (user_id, other_user_id)
  select id, p_member_id from public.profiles where status = 'admin'
  union all
  select p_member_id, id from public.profiles where status = 'admin'
  on conflict do nothing;
$$;

-- A member is connected with the admins when their profile goes live. A trigger rather than part
-- of complete_age_verification, so activating a profile by hand in Studio connects them too.
create or replace function public.connect_new_member_with_admins()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.connect_with_admins(new.id);
  return null;
end;
$$;

create trigger connect_new_member_with_admins
  after update of status on public.profiles
  for each row
  when (old.status = 'approved' and new.status = 'active')
  execute function public.connect_new_member_with_admins();

-- Members who are already past the age check.
select public.connect_with_admins(id)
from public.profiles
where status in ('active', 'disabled', 'suspended');

-- functions ---------------------------------------------------------------

-- Sends an intro: the pending connection, its first message, and both people's
-- connection_secrets rows. If the caller has already sent this person an intro, it does nothing,
-- so a retry after a dropped connection is harmless.
create or replace function public.send_intro(
  p_recipient_id uuid,
  p_looking_for text[],
  p_content jsonb
)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
  recipient public.profiles;
begin
  -- Locking the initiator's row makes their intros one at a time, so the daily limit holds.
  perform from public.profiles where id = uid and status = 'active' for update;
  if not found then
    raise exception 'Your profile needs to be live to send intros.';
  end if;

  if exists (
    select 1 from public.connections where initiator_id = uid and recipient_id = p_recipient_id
  ) then
    return;
  end if;

  select * into recipient from public.profiles where id = p_recipient_id;
  if recipient.status is distinct from 'active' or uid = p_recipient_id then
    raise exception 'Intros can only go to members whose profiles are live.';
  end if;

  if exists (
    select 1 from public.connections where initiator_id = p_recipient_id and recipient_id = uid
  ) then
    raise exception 'This person has already sent you an intro.';
  end if;

  -- 3 intros a day, where days start at 3am UTC (the quietest hour, and simple).
  if (
    select count(*) from public.connections
    where initiator_id = uid
      and created_at >= (date_trunc('day', now() at time zone 'UTC' - interval '3 hours')
                         + interval '3 hours') at time zone 'UTC'
  ) >= 3 then
    raise exception 'You can send 3 intros a day.' using errcode = 'program_limit_exceeded';
  end if;

  if coalesce(cardinality(p_looking_for), 0) = 0
    or not coalesce(p_looking_for <@ recipient.looking_for, false)
  then
    raise exception 'Pick what to connect on from what this person is looking for.';
  end if;

  perform public.check_message_content(p_content);

  insert into public.connections (initiator_id, recipient_id, looking_for)
  values (uid, p_recipient_id, p_looking_for);

  insert into public.messages (sender_id, recipient_id, content)
  values (uid, p_recipient_id, p_content);

  -- Either row may already exist from a dismissal.
  insert into public.connection_secrets (user_id, other_user_id)
  values (uid, p_recipient_id), (p_recipient_id, uid)
  on conflict do nothing;
end;
$$;

-- Accepts an intro the caller received. Accepting again does nothing. A declined intro can't be
-- accepted (see the open questions in docs/database.md).
create or replace function public.accept_intro(p_initiator_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
begin
  if public.can_message((select status from public.profiles where id = uid)) is not true then
    raise exception 'Your profile needs to be live to accept intros.';
  end if;

  if exists (
    select 1 from public.connection_secrets
    where user_id = uid and other_user_id = p_initiator_id and declined_at is not null
  ) then
    raise exception 'You declined this intro already.';
  end if;

  update public.connections set status = 'accepted'
  where initiator_id = p_initiator_id and recipient_id = uid and status <> 'ended';
  if not found then
    raise exception 'There is no intro from this person.';
  end if;
end;
$$;

-- Declines a pending intro the caller received. Only the caller's connection_secrets row
-- changes, so the initiator isn't told. Declining again does nothing.
create or replace function public.decline_intro(p_initiator_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
begin
  if not exists (
    select 1 from public.connections
    where initiator_id = p_initiator_id and recipient_id = uid and status = 'pending'
  ) then
    raise exception 'There is no intro from this person waiting for you.';
  end if;

  update public.connection_secrets set declined_at = coalesce(declined_at, now())
  where user_id = uid and other_user_id = p_initiator_id;
end;
$$;

-- Sends a message in an accepted connection. Sending the same id again does nothing, so a retry
-- after a dropped connection is harmless.
create or replace function public.send_message(p_id uuid, p_recipient_id uuid, p_content jsonb)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
begin
  if exists (
    select 1 from public.messages
    where id = p_id and sender_id = uid and recipient_id = p_recipient_id
  ) then
    return;
  end if;

  perform public.check_message_content(p_content);

  if public.can_message((select status from public.profiles where id = uid)) is not true then
    raise exception 'Your profile needs to be live to send messages.';
  end if;

  if not exists (
    select 1 from public.connections
    where status = 'accepted'
      and (initiator_id, recipient_id) in ((uid, p_recipient_id), (p_recipient_id, uid))
  ) then
    raise exception 'You can only message people whose intro was accepted.';
  end if;

  if (select status from public.profiles where id = p_recipient_id) = 'deleted' then
    raise exception 'This person has deleted their account.';
  end if;

  insert into public.messages (id, sender_id, recipient_id, content)
  values (p_id, uid, p_recipient_id, p_content);
end;
$$;

-- Ends an accepted connection: neither can message the other any more, and it can't be undone.
-- An `ended` message from the caller records who ended it and when. The connection with the
-- admins can't be ended.
create or replace function public.end_connection(p_user_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
begin
  if exists (select 1 from public.profiles where id in (uid, p_user_id) and status = 'admin') then
    raise exception 'The conversation with the admins can''t be ended.';
  end if;

  update public.connections set status = 'ended'
  where status = 'accepted'
    and (initiator_id, recipient_id) in ((uid, p_user_id), (p_user_id, uid));
  if not found then
    raise exception 'There is no connection with this person to end.';
  end if;

  insert into public.messages (sender_id, recipient_id, content)
  values (uid, p_user_id, '{"type": "ended"}');
end;
$$;

-- Moves the caller's read watermark for the conversation with p_user_id forward to p_read_at,
-- the time they read it on their device (which may be a while ago, if they were offline), but
-- never past now() and never back.
create or replace function public.mark_read(p_user_id uuid, p_read_at timestamptz)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
begin
  update public.connection_secrets
  set last_read_at = greatest(last_read_at, least(p_read_at, now()))
  where user_id = uid and other_user_id = p_user_id;
  if not found then
    raise exception 'There is no conversation with this person.';
  end if;
end;
$$;

-- Dismisses someone in search, or undoes it. It only hides them from the caller's own search.
create or replace function public.set_dismissed(p_user_id uuid, p_dismissed boolean)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
begin
  insert into public.connection_secrets (user_id, other_user_id, dismissed_at)
  values (uid, p_user_id, case when p_dismissed then now() end)
  on conflict (user_id, other_user_id) do update set dismissed_at = excluded.dismissed_at;
end;
$$;

-- The profiles of the people the caller has connections with, as their profile shows them: the
-- age rather than the birth date, and no status, timestamps or vetting answers. `is_admin` marks
-- the conversation with the admins. The birthday counts only once the birth month is over, so
-- nobody is shown older than they are (like ageFrom() in the app: keep the two in step).
create or replace function public.get_connected_profiles()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  uid uuid := public.require_auth_uid();
begin
  return coalesce(
    (
      select jsonb_agg(jsonb_build_object(
        'id', p.id,
        'name', p.name,
        'pronouns', p.pronouns,
        'tagline', p.tagline,
        'bio', p.bio,
        'location', p.location,
        'gender', p.gender,
        'sexuality', p.sexuality,
        'looking_for', p.looking_for,
        'age', extract(
          year from age(now(), make_date(p.birth_year, p.birth_month, 1) + interval '1 month')
        )::int,
        'photos', p.photos,
        'is_admin', p.status = 'admin'
      ))
      from public.connections c
      join public.profiles p
        on p.id = case when c.initiator_id = uid then c.recipient_id else c.initiator_id end
      where uid in (c.initiator_id, c.recipient_id)
    ),
    '[]'
  );
end;
$$;

